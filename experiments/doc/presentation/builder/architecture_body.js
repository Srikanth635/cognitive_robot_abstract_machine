// Slide 8: the four components, two contracts and the base layer, as approved in Phase 1.

const L = require("./layouts.js");
const K = L.K, TINT = L.TINT, FONT = L.FONT, W = L.W;
const COMPONENT = L.theme.components;

function componentCard(pres, slide, C, number, name, module, lines, colour, x, y, w, h, objectName) {
  L.card(pres, slide, x, y, w, h, colour, K.background, objectName + " card");
  L.marker(pres, slide, number, x + 0.18, y + 0.18, 0.32, colour, objectName);
  slide.addText(name, { x: x + 0.58, y: y + 0.14, w: w - 0.62, h: 0.4, isTextBox: true, margin: 0, fontSize: 13, bold: true, color: colour, fontFace: FONT.heading, valign: "middle", objectName: objectName + " name" });
  slide.addText(module, { x: x + 0.6, y: y + 0.5, w: w - 0.75, h: 0.26, isTextBox: true, margin: 0, fontSize: 9, color: C.text2, fontFace: FONT.mono, valign: "middle", objectName: objectName + " module" });
  slide.addText(lines, { x: x + 0.18, y: y + 0.84, w: w - 0.36, h: h - 0.95, isTextBox: true, margin: 0, fontSize: 10.5, color: C.text1, valign: "top", objectName: objectName + " role" });
}

module.exports = function architecture(pres, C, s) {
  const bw = 2.7, bh = 1.5, rowGap = 0.6;
  const px = 3.0, py = 1.7, pw = 7.4;
  const ph = 0.4 + bh + rowGap + bh + 0.25;
  const row1 = py + 0.4, row2 = row1 + bh + rowGap;
  const leftCol = px + 0.3, rightCol = px + pw - 0.3 - bw;
  const graph = { x: 0.5, w: px - 0.3 - 0.5 };
  const model = { x: px + pw + 0.3, w: W - 0.5 - (px + pw + 0.3) };

  s.addShape(pres.ShapeType.roundRect, { x: px, y: py, w: pw, h: ph, rectRadius: 0.15, fill: { color: TINT.blue }, line: { color: K.navy, width: 1.5, dashType: "dash" }, objectName: "llm_reasoner package" });
  L.pill(pres, s, "llm_reasoner", px + 0.25, py - 0.15, 1.3, 0.3, K.navy, "package name");

  componentCard(pres, s, C, "1", "Resolver", "resolver/", "A krrood query and an optional task in; a resolved designator with the grounds of every choice out.", COMPONENT.resolver, leftCol, row1, bw, bh, "resolver");
  componentCard(pres, s, C, "2", "Clients", "clients/", "The tool loop with the language model, prompt caching and usage; a scripted client for tests.", COMPONENT.language_model, rightCol, row1, bw, bh, "clients");
  componentCard(pres, s, C, "3", "World injector", "world/", "What is in this world now: kinds, individuals, holders and predicates, read through krrood alone.", COMPONENT.world_injector, leftCol, row2, bw, bh, "world injector");
  componentCard(pres, s, C, "4", "Knowledge component", "knowledge/", "What an action normally involves: generated by the model, admitted only if the ontology accepts it.", COMPONENT.knowledge, rightCol, row2, bw, bh, "knowledge component");

  L.card(pres, s, model.x, row1 + 0.35, model.w, 1.05, K.line, TINT.grey, "language model card");
  s.addText("Language model", { x: model.x + 0.2, y: row1 + 0.35, w: model.w - 0.4, h: 1.05, isTextBox: true, margin: 0, fontSize: 14, bold: true, color: C.text1, fontFace: FONT.heading, valign: "middle", objectName: "language model" });
  L.card(pres, s, graph.x, row2 + 0.35, graph.w, 1.05, K.line, TINT.grey, "symbol graph card");
  s.addText([
    { text: "krrood SymbolGraph", options: { bold: true, breakLine: true, fontFace: FONT.heading } },
    { text: "the live world", options: { color: C.text2, fontSize: 11 } },
  ], { x: graph.x + 0.2, y: row2 + 0.35, w: graph.w - 0.4, h: 1.05, isTextBox: true, margin: 0, fontSize: 14, color: C.text1, valign: "middle", objectName: "symbol graph" });

  s.addText("Caller: a plan, cram_viz, a test", { x: leftCol + 1.7, y: py - 0.45, w: 4, h: 0.28, isTextBox: true, margin: 0, fontSize: 11, italic: true, color: C.text2, valign: "middle", objectName: "caller" });
  L.arrow(pres, s, leftCol + 1.5, py - 0.3, leftCol + 1.5, row1, COMPONENT.resolver, "caller to resolver");

  const lineX = leftCol + 0.5;
  L.arrow(pres, s, lineX, row1 + bh, lineX, row2, COMPONENT.world_injector, "resolver to world");
  L.pill(pres, s, "WorldAccess 1.0", lineX + 0.12, row1 + bh + rowGap / 2 - 0.15, 1.35, 0.3, COMPONENT.world_injector, "world contract");
  L.arrow(pres, s, leftCol + 1.8, row1 + bh, rightCol + 0.35, row2, COMPONENT.knowledge, "resolver to knowledge");
  L.pill(pres, s, "KnowledgeAccess 1.3", leftCol + bw + 0.6, row1 + bh + 0.02, 1.65, 0.3, COMPONENT.knowledge, "knowledge contract");
  L.arrow(pres, s, leftCol + bw, row1 + 0.5, rightCol, row1 + 0.5, COMPONENT.language_model, "resolver to clients");
  L.pill(pres, s, "prompts", leftCol + bw + 0.12, row1 + 0.12, rightCol - leftCol - bw - 0.24, 0.3, COMPONENT.language_model, "prompt protocol");
  const upX = rightCol + bw - 0.6;
  L.arrow(pres, s, upX, row2, upX, row1 + bh, COMPONENT.language_model, "knowledge to clients");
  L.pill(pres, s, "completion", upX - 1.15, row1 + bh + 0.3, 0.95, 0.3, COMPONENT.language_model, "completion label");
  L.arrow(pres, s, rightCol + bw, row1 + 0.87, model.x, row1 + 0.87, COMPONENT.language_model, "clients to model");
  s.addText("API", { x: rightCol + bw, y: row1 + 0.55, w: model.x - rightCol - bw, h: 0.28, isTextBox: true, margin: 0, fontSize: 9.5, bold: true, color: COMPONENT.language_model, align: "center", valign: "middle", objectName: "api label" });
  L.arrow(pres, s, leftCol, row2 + 0.87, graph.x + graph.w, row2 + 0.87, COMPONENT.world_injector, "world to graph");
  s.addText("reads", { x: graph.x + graph.w, y: row2 + 0.55, w: leftCol - graph.x - graph.w, h: 0.28, isTextBox: true, margin: 0, fontSize: 9.5, bold: true, color: COMPONENT.world_injector, align: "center", valign: "middle", objectName: "reads label" });

  L.band(pres, s, "Base layer", "llm_reasoner imports krrood only, never a world model, a robot or a plan package; the world is read through krrood's symbol graph.", 0.5, py + ph + 0.25, W - 1.0, 0.55, "base layer note");
};
