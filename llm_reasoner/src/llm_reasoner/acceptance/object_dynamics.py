"""
Acceptance rules of the object-dynamics module: the command-to-prediction pathway,
represented estimates, sensorimotor memories and transfers of adaptation.
"""

from __future__ import annotations

from enum import StrEnum

from krrood.entity_query_language.factories import (
    and_,
    contains,
    flat_variable,
    not_,
    or_,
)
from typing_extensions import Any

from llm_reasoner.acceptance.rules import FragmentRule, StructureRule
from llm_reasoner.ontologies.predictive_manipulation import core, object_dynamics

# %% rule names


class ObjectDynamicsRule(StrEnum):
    """
    The acceptance rules of the object-dynamics module.
    """

    COMPOSITION_PREDICTS_WITH_ITS_FORWARD_MODEL = (
        "composition_predicts_with_its_forward_model"
    )
    """
    The sensory consequences a composition predicts are generated by its own forward
    model; otherwise the command-to-prediction pathway is broken.
    """

    COMPOSITION_DYNAMICS_USES_ITS_COPY = "composition_dynamics_uses_its_copy"
    """
    The dynamics model of a composition uses the composition's efference copy, which is
    what lets it predict the load the command will produce.
    """

    ESTIMATE_SERVES_ONE_PURPOSE = "estimate_serves_one_purpose"
    """
    A perceptual judgment must not silently become the estimate used for motor
    scaling: one estimate is not held for both purposes.
    """

    DISSOCIATION_COHERENT = "dissociation_coherent"
    """
    A dissociation relates two distinct estimates, each held by the representation it
    is said to belong to.
    """

    RETAINED_UPDATE_IN_ITS_MEMORY = "retained_update_in_its_memory"
    """
    An update retained in a sensorimotor memory changes a representation that memory
    stores.
    """

    TRANSFER_COMPARES_MATCHED_PERTURBATIONS = "transfer_compares_matched_perturbations"
    """
    A transfer of adaptation compares two distinct perturbations of the same kind that
    are matched with each other.
    """

    REPRESENTATION_COVERS_ESTIMATED_ROLES = "representation_covers_estimated_roles"
    """
    A representation names every participant whose properties its estimates describe.
    """


# %% internal model composition


class CompositionPredictsWithItsForwardModel(
    FragmentRule[object_dynamics.InternalModelComposition]
):
    """
    Every sensory consequence a composition predicts is generated by its forward
    model.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.COMPOSITION_PREDICTS_WITH_ITS_FORWARD_MODEL

    @property
    def reason(self) -> str:
        return "predicts a sensory consequence another forward model generates"

    def violating(self, subject: Any) -> Any:
        prediction = flat_variable(subject.predicts_sensory_consequence)
        return and_(
            subject.uses_forward_model != None,
            not_(contains(prediction.generated_by, subject.uses_forward_model)),
        )


class CompositionDynamicsUsesItsCopy(
    FragmentRule[object_dynamics.InternalModelComposition]
):
    """
    The dynamics model of a composition uses every efference copy of the composition.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.COMPOSITION_DYNAMICS_USES_ITS_COPY

    @property
    def reason(self) -> str:
        return "uses_dynamics_model does not use the composition's efference copy"

    def violating(self, subject: Any) -> Any:
        copy = flat_variable(subject.uses_efference_copy)
        return and_(
            subject.uses_dynamics_model != None,
            not_(contains(subject.uses_dynamics_model.uses_efference_copy, copy)),
        )


# %% represented estimates


def representations(
    structure: object_dynamics.ObjectDynamicsPhaseStructure,
) -> list[core.EstimateRepresentation]:
    """
    :return: The structure's internal models that hold estimates.
    """
    return [
        model
        for model in structure.defines_internal_model
        if isinstance(model, core.EstimateRepresentation)
    ]


class EstimateServesOnePurpose(
    StructureRule[object_dynamics.ObjectDynamicsPhaseStructure]
):
    """
    No estimate is held both for sensorimotor control and for perceptual judgment.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.ESTIMATE_SERVES_ONE_PURPOSE

    @property
    def reason(self) -> str:
        return "one estimate is held for sensorimotor control and perceptual judgment"

    def is_violated_by(
        self, fragment: object_dynamics.ObjectDynamicsPhaseStructure
    ) -> bool:
        def held_for(purpose: object_dynamics.RepresentationPurpose) -> set[int]:
            return {
                id(estimate)
                for representation in representations(fragment)
                if isinstance(representation, object_dynamics.ContextualRepresentation)
                and representation.has_purpose == purpose
                for estimate in representation.holds_estimate
            }

        return bool(
            held_for(object_dynamics.RepresentationPurpose.SENSORIMOTOR_CONTROL)
            & held_for(object_dynamics.RepresentationPurpose.PERCEPTUAL_JUDGMENT)
        )


class DissociationCoherent(FragmentRule[object_dynamics.RepresentationDissociation]):
    """
    A dissociation's estimates are distinct and held by their own representations.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.DISSOCIATION_COHERENT

    @property
    def reason(self) -> str:
        return "the estimates are the same, or one is not held by its representation"

    def violating(self, subject: Any) -> Any:
        sensorimotor = subject.has_sensorimotor_representation
        perceptual = subject.has_perceptual_representation
        return or_(
            and_(
                subject.sensorimotor_estimate != None,
                subject.sensorimotor_estimate == subject.perceptual_estimate,
            ),
            and_(
                sensorimotor != None,
                subject.sensorimotor_estimate != None,
                not_(
                    contains(sensorimotor.holds_estimate, subject.sensorimotor_estimate)
                ),
            ),
            and_(
                perceptual != None,
                subject.perceptual_estimate != None,
                not_(contains(perceptual.holds_estimate, subject.perceptual_estimate)),
            ),
        )


# %% memory and transfer


class RetainedUpdateInItsMemory(FragmentRule[object_dynamics.RetainedModelUpdate]):
    """
    A retained update changes a representation its memory stores.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.RETAINED_UPDATE_IN_ITS_MEMORY

    @property
    def reason(self) -> str:
        return "updates_representation is not stored in persists_in"

    def violating(self, subject: Any) -> Any:
        return and_(
            subject.updates_representation != None,
            subject.persists_in != None,
            not_(
                contains(
                    subject.persists_in.stores_representation,
                    subject.updates_representation,
                )
            ),
        )


class TransferComparesMatchedPerturbations(
    FragmentRule[object_dynamics.DynamicsTransfer]
):
    """
    A transfer compares two distinct perturbations of one kind matched with each
    other.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.TRANSFER_COMPARES_MATCHED_PERTURBATIONS

    @property
    def reason(self) -> str:
        return "the perturbations are the same, of different kinds, or not matched"

    def violating(self, subject: Any) -> Any:
        source, target = subject.from_perturbation, subject.to_perturbation
        return and_(
            source != None,
            target != None,
            or_(
                source == target,
                source.has_perturbation_kind != target.has_perturbation_kind,
                not_(contains(source.matched_with, target)),
            ),
        )


class RepresentationCoversEstimatedRoles(
    FragmentRule[object_dynamics.ContextualRepresentation]
):
    """
    A representation represents every participant its estimates concern.
    """

    @property
    def name(self) -> StrEnum:
        return ObjectDynamicsRule.REPRESENTATION_COVERS_ESTIMATED_ROLES

    @property
    def reason(self) -> str:
        return "an estimate concerns a participant represents_role omits"

    def violating(self, subject: Any) -> Any:
        estimate = flat_variable(subject.holds_estimate)
        role = flat_variable(estimate.parameter_on_role)
        return not_(contains(subject.represents_role, role))
