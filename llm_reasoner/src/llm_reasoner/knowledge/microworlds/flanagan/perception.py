"""
Perceptual sensory attenuation kept separate from action control.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum

from llm_reasoner.knowledge.microworlds.flanagan.core import (
    ForwardModel,
    MagnitudeRange,
    ScientificAssertion,
    SensoryEventPrediction,
    SensoryObservationType,
    TemporalWindow,
)
from llm_reasoner.knowledge.microworlds.flanagan.namespaces import FlanaganNamespace
from llm_reasoner.knowledge.ontological.decorators import (
    KnowledgeEntity,
    ontological,
    prop,
    value_partition,
)

PERCEPTION = FlanaganNamespace.PERCEPTION
"""
Namespace for perceptual attenuation concepts.
"""

# %% event origin


@value_partition(PERCEPTION + "EventOrigin")
class EventOrigin(StrEnum):
    """
    Whether a sensory event is generated by the perceiver's own action.
    """

    SELF_GENERATED = "self_generated"
    """
    The event results from the perceiver's predicted action.
    """

    EXTERNAL = "external"
    """
    The event is generated independently of the perceiver's action.
    """


# %% sensory attenuation


@ontological(iri=PERCEPTION + "AttenuatedPerceptualResponse")
@dataclass(eq=False)
class AttenuatedPerceptualResponse(KnowledgeEntity):
    """
    A reduced perceptual response to predicted self-generated contact.
    """

    observation: SensoryObservationType | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasObservation",
    )
    """
    The observation whose perceptual response is attenuated.
    """

    attenuation_amount: MagnitudeRange | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasAttenuationAmount",
    )
    """
    The reduction in perceptual response relative to an external event.
    """


@ontological(iri=PERCEPTION + "SensoryAttenuation")
@dataclass(eq=False)
class SensoryAttenuation(ScientificAssertion):
    """
    Perceptual attenuation centered on a predicted contact event.
    """

    predicted_contact: SensoryEventPrediction | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasPredictedContact",
    )
    """
    The predicted sensory consequence of the forthcoming contact.
    """

    event_origin: EventOrigin | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasEventOrigin",
    )
    """
    Whether the contact is self-generated or externally generated.
    """

    attenuation_window: TemporalWindow | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasAttenuationWindow",
    )
    """
    The interval around predicted contact in which attenuation occurs.
    """

    attenuated_response: AttenuatedPerceptualResponse | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasAttenuatedResponse",
    )
    """
    The reduced perceptual response observed within the window.
    """


@ontological(iri=PERCEPTION + "AttenuationControlRelationship")
@dataclass(eq=False)
class AttenuationControlRelationship(ScientificAssertion):
    """
    The unresolved relation between attenuation and action-control prediction.
    """

    attenuation: SensoryAttenuation | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasAttenuation",
    )
    """
    The perceptual attenuation process under comparison.
    """

    action_control_model: ForwardModel | None = prop(
        functional=True,
        min_count=1,
        iri=PERCEPTION + "hasActionControlModel",
    )
    """
    The action-control model proposed to share a prediction mechanism.
    """


@ontological(iri=PERCEPTION + "SensoryAttenuationProfile")
@dataclass(eq=False)
class SensoryAttenuationProfile(KnowledgeEntity):
    """
    The attenuation effects and unresolved control links under study.
    """

    attenuations: list[SensoryAttenuation] = prop(
        min_count=1,
        default_factory=list,
        iri=PERCEPTION + "hasSensoryAttenuation",
    )
    """
    The perceptual attenuation effects represented by the profile.
    """

    control_relationships: list[AttenuationControlRelationship] = prop(
        default_factory=list,
        iri=PERCEPTION + "hasControlRelationship",
    )
    """
    The unresolved candidate links to action-control prediction.
    """
