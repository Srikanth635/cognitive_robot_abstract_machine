"""
Hypotheses: the epistemic wrapper around generated content.

WHY THE WRAPPER IS SEPARATE FROM THE CONTENT
--------------------------------------------
Two kinds of knowledge with different authority and different rates of change.
The microworld classes carry OBJECT-LEVEL knowledge: what a pouring phase is.
This package carries META-LEVEL knowledge: that this particular structure was
generated by a given model at a given time, under given module versions, with
given assumptions, and has not been refuted.

Keeping them apart matters because the meta level changes with engineering needs
rather than with the theory of the domain, and because a record stays queryable
alongside its content -- one query can ask for phases whose terminating event is
a slip, from hypotheses validated under module version N or later.

MICROWORLD-AGNOSTIC
-------------------
Nothing here imports a microworld, and nothing here imports ``resolver``. The
first keeps the layer reusable for the next microworld; the second is what stops
generic knowledge acquiring a dependency on situated state.

MODULES
-------
``status``
    ``HypothesisStatus`` and ``Defeater``. The full vocabulary exists before
    anything writes ``REFUTED``, because retrofitting the concept of rejection
    is expensive while adding a status value is not.
``provenance``
    ``Provenance`` and ``CacheKey``, plus ``Exchange`` re-exported from
    ``clients``, which is where the record of a model call belongs. The whole
    attempt log is kept, not just the exchange that worked: a hypothesis needing two repairs
    carries evidence about the ontology, not only about the model. The cache key
    deliberately carries no episodic component.
``scope``
    ``KnowledgeScope`` and ``collect_reachable``. Structural separation from the
    world model, enforced at admission -- the failure it prevents is silent, so
    reporting it after the fact would leave every later query wrong.
``serialization``
    Records to plain data and back, using the same flat fragment graph a model
    emits during generation. Values are self-describing, so a stored record can
    be read without deriving a schema against a model that may have moved on.
``store``
    ``HypothesisStore`` with in-memory and file-backed implementations. Stale
    and superseded are kept distinct: a record goes stale when the ontology
    moves, and is superseded only once a replacement exists. Nothing is ever
    deleted, because a past resolution cited what it leaned on.
``record``
    ``HypothesisRecord``, ``ValidationReport`` and ``Assumption``. Assumptions
    are the most useful thing a hypothesis tells the resolver: everything else
    is structure it may take or leave, while an assumption must be checked
    against the world before the hypothesis applies at all.

DEFERRED
--------
Nothing writes ``REFUTED`` yet, and ``HypothesisRecord.refute`` has no caller.
Recording resolver rejections as defeaters is the next step, and the shape is
already here so that step is additive.
"""

