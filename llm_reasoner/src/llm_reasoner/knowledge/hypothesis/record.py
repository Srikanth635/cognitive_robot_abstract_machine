"""
The hypothesis record: generated content plus everything true *about* it.

TWO LEVELS, ONE QUERY
---------------------
The microworld classes carry object-level knowledge -- what a pouring phase is. This
module carries meta-level knowledge -- that this particular structure was generated by
a given model under given module versions, passed its constraints, and has not been
refuted.

They are kept apart because they change for different reasons and on different
timescales, and because reifying epistemic status inside the ontology would cost a level
of indirection on every fragment. Keeping the wrapper in Python costs nothing and still
allows one query to span both: validated hypotheses, generated under module version N or
later, whose phases terminate on a slip.

MICROWORLD-AGNOSTIC BY CONSTRUCTION
-----------------------------------
Nothing here imports a microworld. Assumptions are recorded by whoever generated the
hypothesis, because knowing which fragments are assumptions requires knowing the
microworld's own vocabulary, and this layer must work for the next one too.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping, Optional
from uuid import uuid4

from llm_reasoner.knowledge.hypothesis.provenance import CacheKey, Provenance
from llm_reasoner.knowledge.hypothesis.scope import KnowledgeScope, collect_reachable
from llm_reasoner.knowledge.hypothesis.status import Defeater, HypothesisStatus
from llm_reasoner.knowledge.ontological.decorators import ConceptReference


@dataclass(frozen=True)
class Assumption:
    """
    Something the hypothesis presupposes rather than establishes.

    The most useful thing a hypothesis tells the resolver. Everything else is structure
    the resolver may take or leave; an assumption is a claim about the world that must
    be checked before the hypothesis applies at all, and reported when it cannot be.
    """

    fragment_id: str
    """
    The requirement that carries the assumption.
    """

    description: str
    """
    What is presupposed, in the microworld's own terms.
    """

    on_roles: tuple[str, ...] = ()
    """
    Identities of the role slots it predicates over, so the resolver knows what it must
    have bound before the assumption can even be evaluated.
    """


@dataclass(frozen=True)
class ValidationReport:
    """
    The outcome of running a microworld's acceptance constraints.
    """

    checks_run: int = 0
    errors: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()
    repair_attempts: int = 0
    """
    How many corrections were needed before this outcome.
    """

    @property
    def admissible(self) -> bool:
        """:return: Whether the hypothesis may be served.

        Warnings do not block. They flag content that is structurally legal but
        probably not what was meant -- two phases the controller cannot tell
        apart, a margin over an unrelated threshold -- and refusing on those
        would reject hypotheses that are merely imperfect.
        """
        return not self.errors

    @classmethod
    def from_violations(
        cls, violations: Iterable[Any], checks_run: int = 0, repair_attempts: int = 0
    ) -> "ValidationReport":
        """
        Build a report from constraint-suite output.

        Takes anything with ``severity`` and a string form, so this layer stays
        independent of which suite produced it.
        """
        collected = list(violations)
        return cls(
            checks_run=checks_run,
            errors=tuple(
                str(v) for v in collected if getattr(v, "severity", "error") == "error"
            ),
            warnings=tuple(
                str(v) for v in collected if getattr(v, "severity", None) == "warning"
            ),
            repair_attempts=repair_attempts,
        )


@dataclass
class HypothesisRecord:
    """
    One stereotypical hypothesis, with everything known about its standing.
    """

    action_type: ConceptReference
    """
    The task this is a hypothesis about.

    The first half of the cache key, and what the query surface retrieves by.
    """

    scope: KnowledgeScope
    """
    The fragments, in a container closed to episodic content.
    """

    provenance: Provenance
    root_id: Optional[str] = None
    """
    Identity of the top-level fragment.

    Everything else hangs off it, so discarding this node discards the hypothesis.
    """

    record_id: str = field(default_factory=lambda: uuid4().hex[:12])
    status: HypothesisStatus = HypothesisStatus.CANDIDATE
    validation: ValidationReport = field(default_factory=ValidationReport)
    assumptions: tuple[Assumption, ...] = ()
    defeaters: tuple[Defeater, ...] = ()

    supersedes: Optional[str] = None
    superseded_by: Optional[str] = None
    """
    Links rather than deletion, so a past resolution stays explainable against the
    knowledge as it stood at the time.
    """

    # -- construction ------------------------------------------------------

    @classmethod
    def from_root(
        cls,
        root: Any,
        action_type: ConceptReference,
        provenance: Provenance,
        label: str = "",
        **kwargs: Any,
    ) -> "HypothesisRecord":
        """
        Build a record by walking everything reachable from a root fragment.

        Traversal follows declared fields only, and admission refuses anything
        occurrence-level, so a generated graph is checked for scope violations as it is
        wrapped rather than after something has already queried it.
        """
        scope = KnowledgeScope(label=label or getattr(root, "label", ""))
        scope.admit_all(collect_reachable(root))
        return cls(
            action_type=action_type,
            scope=scope,
            provenance=provenance,
            root_id=getattr(root, "local_id", None),
            **kwargs,
        )

    # -- identity and staleness -------------------------------------------

    @property
    def cache_key(self) -> CacheKey:
        return CacheKey.of(self.action_type.iri, self.provenance)

    def is_stale(
        self,
        module_versions: Mapping[str, str],
        prompt_version: str | None = None,
    ) -> bool:
        """:return: Whether the knowledge contract has moved since generation."""
        return self.cache_key.invalidated_by(module_versions, prompt_version)

    @property
    def root(self) -> Optional[Any]:
        return self.scope.by_id(self.root_id) if self.root_id else None

    # -- transitions -------------------------------------------------------

    def validated(self, report: ValidationReport) -> "HypothesisRecord":
        """
        Record a validation outcome and move to the status it implies.
        """
        self.validation = report
        self.status = (
            HypothesisStatus.VALIDATED
            if report.admissible
            else HypothesisStatus.REFUTED
        )
        return self

    def refute(self, defeater: Defeater) -> "HypothesisRecord":
        """
        Record a defeater and mark the hypothesis refuted.

        Nothing calls this yet: recording resolver rejections is deferred. It
        exists so that when the resolver does start reporting them, the target
        already has the right shape.
        """
        self.defeaters = (*self.defeaters, defeater)
        self.status = HypothesisStatus.REFUTED
        return self

    def supersede(self, replacement: "HypothesisRecord") -> "HypothesisRecord":
        """
        Mark this hypothesis replaced, keeping both and the link between.
        """
        self.status = HypothesisStatus.SUPERSEDED
        self.superseded_by = replacement.record_id
        replacement.supersedes = self.record_id
        return self

    # -- serving -----------------------------------------------------------

    @property
    def servable(self) -> bool:
        """:return: Whether the query surface should offer this by default.

        Only validated hypotheses. A candidate has not been checked, a
        superseded one describes a model no longer in force, and a refuted one
        is retained as evidence rather than as guidance.
        """
        return self.status is HypothesisStatus.VALIDATED

    def cite(self, fragment: Any) -> str:
        """
        Render a citation for a fragment served from this hypothesis.

        Every answer the resolver receives carries this, so a resolution can state which
        stereotypical assumptions it leaned on rather than merely asserting a
        conclusion.
        """
        local = getattr(fragment, "local_id", "?")
        label = getattr(fragment, "label", "") or type(fragment).__name__
        return f"{label} [{self.record_id}/{local}]"


__all__ = ["Assumption", "HypothesisRecord", "ValidationReport"]
