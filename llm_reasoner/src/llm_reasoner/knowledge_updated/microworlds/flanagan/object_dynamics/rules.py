# %% the rules


class ObjectDynamicsRule(StrEnum):
    """
    A rule an object-dynamics phase structure must satisfy.
    """

    # -- the command pathway ----------------------------------------------

    DYNAMICS_MODEL_NOT_GIVEN_THE_COPY = "dynamics_model_not_given_the_copy"
    """
    The dynamics model of a pathway must use the efference copy of that pathway. Otherwise
    the load it predicts is not the load of the command that was copied.
    """

    PREDICTION_NOT_FROM_THE_COMPOSITIONS_FORWARD_MODEL = (
        "prediction_not_from_the_compositions_forward_model"
    )
    """
    A sensory consequence predicted by a pathway must be generated by the forward model of
    that pathway, or the pathway predicts nothing it can vouch for.
    """

    # -- represented content ----------------------------------------------

    ESTIMATE_HELD_BY_NO_REPRESENTATION = "estimate_held_by_no_representation"
    """
    An estimate needs a representation to supply its coordinate frame, its purpose and the
    participants it is about.
    """

    ESTIMATE_SERVES_TWO_PURPOSES = "estimate_serves_two_purposes"
    """
    A perceptual judgment must not silently become the estimate used for motor scaling.
    """

    REPRESENTATION_OMITS_ESTIMATED_ROLE = "representation_omits_estimated_role"
    """
    Represented content must identify every participant whose properties or dynamics its
    estimates describe.
    """

    # -- memory -----------------------------------------------------------

    RETAINED_UPDATE_OUTSIDE_ITS_MEMORY = "retained_update_outside_its_memory"
    """
    An update must change a representation that the memory it persists in retains.
    """

    # -- transfer ---------------------------------------------------------

    PERTURBATION_MATCH_NOT_RECIPROCAL = "perturbation_match_not_reciprocal"
    """
    Two perturbations matched physically are matched with each other. A match that only
    one of them states cannot be relied on to compare like with like.
    """

    PERTURBATION_MATCHED_ACROSS_KINDS = "perturbation_matched_across_kinds"
    """
    A load cannot be matched physically with a rotation.
    """

    TRANSFER_BETWEEN_UNMATCHED_PERTURBATIONS = (
        "transfer_between_unmatched_perturbations"
    )
    """
    Adaptation can be compared only across perturbations matched physically. Otherwise a
    difference in transfer may only be a difference in the perturbation.
    """

    TRANSFER_WITHIN_ONE_PERTURBATION = "transfer_within_one_perturbation"
    """
    Transfer from a context to itself compares nothing.
    """

    # -- dissociation -----------------------------------------------------

    SENSORIMOTOR_ESTIMATE_NOT_HELD = "sensorimotor_estimate_not_held"
    """
    The sensorimotor estimate of a dissociation must be held by its sensorimotor
    representation.
    """

    PERCEPTUAL_ESTIMATE_NOT_HELD = "perceptual_estimate_not_held"
    """
    The perceptual estimate of a dissociation must be held by its perceptual
    representation.
    """

    DISSOCIATED_ESTIMATES_NOT_DISTINCT = "dissociated_estimates_not_distinct"
    """
    A dissociation requires two estimates. One estimate cannot disagree with itself.
    """


# %% predicates that no declared kind of rule expresses


def held_estimates(structure: ObjectDynamicsPhaseStructure) -> set[int]:
    """
    Return the identities of the estimates that a representation of the structure holds.
    """
    return identities(
        estimate
        for model in structure.defines_internal_model
        if isinstance(model, EstimateRepresentation)
        for estimate in model.holds_estimate
    )


def structure_has_unheld_estimate(structure: ObjectDynamicsPhaseStructure) -> bool:
    """
    Return whether a declared estimate belongs to no representation.
    """
    held = held_estimates(structure)
    return any(
        isinstance(parameter, Estimate) and id(parameter) not in held
        for parameter in structure.defines_parameter
    )


def structure_reuses_estimate_across_purposes(
    structure: ObjectDynamicsPhaseStructure,
) -> bool:
    """
    Return whether one estimate is held for more than one purpose.
    """
    representations = [
        model
        for model in structure.defines_internal_model
        if isinstance(model, ContextualRepresentation)
    ]
    held_for = [
        identities(
            estimate
            for representation in representations
            if representation.purpose is purpose
            for estimate in representation.holds_estimate
        )
        for purpose in RepresentationPurpose
    ]
    return any(left & right for left, right in combinations(held_for, 2))


def match_is_not_reciprocal(perturbation: DynamicsPerturbation) -> bool:
    """
    Return whether a perturbation is matched with one that does not match it back.
    """
    return any(
        id(perturbation) not in identities(other.matched_with)
        for other in perturbation.matched_with
    )


def match_crosses_kinds(perturbation: DynamicsPerturbation) -> bool:
    """
    Return whether a perturbation is matched with one of another kind.
    """
    return any(
        other.perturbation_kind is not perturbation.perturbation_kind
        for other in perturbation.matched_with
    )


# %% the rules


OBJECT_DYNAMICS_RULES: tuple[AcceptanceRule, ...] = (
    # the command pathway
    Inclusion(
        id=ObjectDynamicsRule.DYNAMICS_MODEL_NOT_GIVEN_THE_COPY,
        applies_to=InternalModelComposition,
        source="efference_copy",
        target="dynamics_model.uses_efference_copy",
    ),
    Inclusion(
        id=ObjectDynamicsRule.PREDICTION_NOT_FROM_THE_COMPOSITIONS_FORWARD_MODEL,
        applies_to=InternalModelComposition,
        source="predicted_sensory_consequence.generated_by",
        target="forward_model",
    ),
    # represented content
    Forbidden(
        id=ObjectDynamicsRule.ESTIMATE_HELD_BY_NO_REPRESENTATION,
        applies_to=ObjectDynamicsPhaseStructure,
        violated_when=structure_has_unheld_estimate,
        message="a declared estimate is held by no representation",
    ),
    Forbidden(
        id=ObjectDynamicsRule.ESTIMATE_SERVES_TWO_PURPOSES,
        applies_to=ObjectDynamicsPhaseStructure,
        violated_when=structure_reuses_estimate_across_purposes,
        message="one estimate is held for both sensorimotor and perceptual purposes",
    ),
    Inclusion(
        id=ObjectDynamicsRule.REPRESENTATION_OMITS_ESTIMATED_ROLE,
        applies_to=ContextualRepresentation,
        source="holds_estimate.parameter_on_role",
        target="represents_role",
    ),
    # memory
    Inclusion(
        id=ObjectDynamicsRule.RETAINED_UPDATE_OUTSIDE_ITS_MEMORY,
        applies_to=RetainedModelUpdate,
        source="updates_representation",
        target="persists_in.stores_representation",
    ),
    # transfer
    Forbidden(
        id=ObjectDynamicsRule.PERTURBATION_MATCH_NOT_RECIPROCAL,
        applies_to=DynamicsPerturbation,
        violated_when=match_is_not_reciprocal,
        message="a perturbation is matched with one that does not match it back",
    ),
    Forbidden(
        id=ObjectDynamicsRule.PERTURBATION_MATCHED_ACROSS_KINDS,
        applies_to=DynamicsPerturbation,
        violated_when=match_crosses_kinds,
        message="a perturbation is matched with one of another kind",
    ),
    Inclusion(
        id=ObjectDynamicsRule.TRANSFER_BETWEEN_UNMATCHED_PERTURBATIONS,
        applies_to=DynamicsTransfer,
        source="to_perturbation",
        target="from_perturbation.matched_with",
    ),
    Distinct(
        id=ObjectDynamicsRule.TRANSFER_WITHIN_ONE_PERTURBATION,
        applies_to=DynamicsTransfer,
        left="from_perturbation",
        right="to_perturbation",
    ),
    # dissociation
    Inclusion(
        id=ObjectDynamicsRule.SENSORIMOTOR_ESTIMATE_NOT_HELD,
        applies_to=RepresentationDissociation,
        source="sensorimotor_estimate",
        target="sensorimotor_representation.holds_estimate",
    ),
    Inclusion(
        id=ObjectDynamicsRule.PERCEPTUAL_ESTIMATE_NOT_HELD,
        applies_to=RepresentationDissociation,
        source="perceptual_estimate",
        target="perceptual_representation.holds_estimate",
    ),
    Distinct(
        id=ObjectDynamicsRule.DISSOCIATED_ESTIMATES_NOT_DISTINCT,
        applies_to=RepresentationDissociation,
        left="sensorimotor_estimate",
        right="perceptual_estimate",
    ),
)
"""
Every rule of the module, in the order of the enumeration that names them.
"""

OBJECT_DYNAMICS_ACCEPTANCE = AcceptanceSuite(
    name="flanagan-object-dynamics",
    ontology=FLANAGAN,
    rules=(*CORE_RULES, *OBJECT_DYNAMICS_RULES),
    checks=(DerivedChecks(FLANAGAN),),
)
