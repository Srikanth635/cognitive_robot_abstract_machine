"""
What makes an object-dynamics phase structure admissible.

Whatever the declarations already say is checked without being written here, among them
the purpose that a kind of representation fixes, the kinds of representation a
dissociation may compare, and that a structure declares everything it refers to. The rules
below are the relationships between several objects that a declaration cannot state. Each
names itself with a member of :class:`ObjectDynamicsRule`, and the documentation of that
member is the reason the rule exists.
"""

