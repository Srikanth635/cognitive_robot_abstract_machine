"""
The path from an outgoing command to the sensory consequences predicted for it.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from llm_reasoner.knowledge_updated.microworlds.flanagan.alignments import (
    DUL,
    related_to,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.core.events import (
    MechanicalEventType,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.core.models import (
    ForwardModel,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.core.prediction import (
    SensoryEventPrediction,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.object_dynamics.commands import (
    EfferenceCopy,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.object_dynamics.representations import (
    DynamicsModel,
)
from llm_reasoner.knowledge_updated.microworlds.flanagan.ontology import OBJECT_DYNAMICS
from llm_reasoner.knowledge_updated.ontological.entities import KnowledgeEntity
from llm_reasoner.knowledge_updated.ontological.properties import relation
from llm_reasoner.knowledge_updated.ontological.vocabulary import EvidenceStatus


@OBJECT_DYNAMICS.concept(
    alignments=(related_to(DUL, "Description"),),
    status=EvidenceStatus.SUPPORTED_INTERPRETATION,
    claims=("FJ-002", "FJ-008"),
)
@dataclass(eq=False)
class InternalModelComposition(KnowledgeEntity):
    """
    How the copy of an outgoing command becomes predicted consequences.

    The copy leads back to the command, and through it to the inverse model that
    selected the command and the state the command pursues.
    """

    efference_copy: Optional[EfferenceCopy] = relation(functional=True, minimum_count=1)
    """
    The internal copy of the outgoing motor command.
    """

    dynamics_model: Optional[DynamicsModel] = relation(functional=True, minimum_count=1)
    """
    The object or limb dynamics used to interpret the command copy.
    """

    forward_model: Optional[ForwardModel] = relation(functional=True, minimum_count=1)
    """
    The model that generates the predicted consequences.
    """

    predicted_mechanical_consequence: list[MechanicalEventType] = relation(
        minimum_count=1
    )
    """
    The mechanical consequences predicted by the composition.
    """

    predicted_sensory_consequence: list[SensoryEventPrediction] = relation(
        minimum_count=1
    )
    """
    The sensory consequences generated by the forward model.
    """
